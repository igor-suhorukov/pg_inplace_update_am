#!/usr/bin/env python3
"""Helpers of the analytical benchmarks (bench/olap/run.sh).

  olap.py tpcgen <h|ds> <sf> <dir>
      TPC-H's (h) or TPC-DS's (ds) data at scale factor <sf>, generated by
      DuckDB's tpch or tpcds extension: <dir>/data/<table>.csv ('|'-separated,
      NULL as an empty field), <dir>/schema.sql, DuckDB's table definitions,
      and <dir>/q/<name>.sql, the queries as the extension has them.  Run
      with DuckDB's Python (/opt/duckdb/bin/python).

  olap.py evict <dir>...
      Drops every file's pages under the directories from the page cache
      (POSIX_FADV_DONTNEED), for a cold run that leaves the rest of the
      host's cache alone.  Dirty pages are not dropped: checkpoint first.

  olap.py report <out>
      <out>/<bench>/results.tsv and load.tsv of each benchmark run into
      <out>/summary.md: load times and sizes, each query's cold and hot
      times per access method, and whether every access method's answer
      is heap's.
"""

import math
import os
import re
import sys


def tpcgen(kind, sf, d):
    import duckdb

    ext, gen, queries, name = {'h': ('tpch', 'dbgen', 'tpch_queries', 'q%02d'),
                               'ds': ('tpcds', 'dsdgen', 'tpcds_queries', 'q%02d')}[kind]
    os.makedirs(os.path.join(d, 'data'), exist_ok=True)
    os.makedirs(os.path.join(d, 'q'), exist_ok=True)
    # a file-backed database: at scale factor 10 the tables do not have to
    # fit in memory
    db = os.path.join(d, 'gen.duckdb')
    if os.path.exists(db):
        os.unlink(db)
    con = duckdb.connect(db, config={'extension_directory': '/opt/duckdb/extensions',
                                     'threads': os.environ.get('DUCKDB_THREADS', '8')})
    con.execute('LOAD %s' % ext)
    con.execute('CALL %s(sf=%s)' % (gen, float(sf)))
    with open(os.path.join(d, 'schema.sql'), 'w') as f:
        for table, sql in con.execute('SELECT table_name, sql FROM duckdb_tables() ORDER BY table_name').fetchall():
            f.write(sql.rstrip().rstrip(';') + ';\n')
            con.execute("COPY %s TO '%s' (FORMAT csv, DELIMITER '|', HEADER false, NULL '')"
                        % (table, os.path.join(d, 'data', table + '.csv')))
    for nr, query in con.execute('SELECT query_nr, query FROM %s() ORDER BY query_nr' % queries).fetchall():
        with open(os.path.join(d, 'q', (name % nr) + '.sql'), 'w') as f:
            f.write(query.rstrip() + '\n')
    con.close()
    os.unlink(db)


def evict(dirs):
    for top in dirs:
        for root, _, files in os.walk(top):
            for fn in files:
                try:
                    fd = os.open(os.path.join(root, fn), os.O_RDONLY)
                except OSError:
                    continue
                try:
                    os.posix_fadvise(fd, 0, 0, os.POSIX_FADV_DONTNEED)
                finally:
                    os.close(fd)


# --- report -------------------------------------------------------------

NUM = re.compile(r'^-?\d+(\.\d+)?(e[-+]?\d+)?$', re.I)


def canonical(path):
    """A query's answer as a sorted list of rows, numbers with a fraction
    rounded to 6 significant digits: parallel plans add floats in another
    order, and the plans of two access methods may differ."""
    try:
        with open(path, errors='replace') as f:
            lines = f.read().splitlines()
    except FileNotFoundError:
        return None
    rows = []
    for line in lines:
        fields = []
        for x in line.split('|'):
            if NUM.match(x) and ('.' in x or 'e' in x.lower()):
                v = float(x)
                x = '%.6g' % v
            fields.append(x)
        rows.append('|'.join(fields))
    return sorted(rows)


def gmean(xs):
    return math.exp(sum(math.log(max(x, 0.001)) for x in xs) / len(xs)) if xs else float('nan')


def fmt_s(ms):
    return '%.2f' % (ms / 1000.0)


def report(out):
    benches = [b for b in ('tpch', 'tpcds', 'clickbench') if os.path.exists(os.path.join(out, b, 'results.tsv'))]
    md = ['# Analytical benchmarks: heap vs iheap', '']
    with open(os.path.join(out, 'settings.txt')) as f:
        md += ['```', f.read().rstrip(), '```', '']
    for b in benches:
        bdir = os.path.join(out, b)
        title = {'tpch': 'TPC-H', 'tpcds': 'TPC-DS', 'clickbench': 'ClickBench'}[b]
        if os.path.exists(os.path.join(bdir, 'scale.txt')):
            with open(os.path.join(bdir, 'scale.txt')) as f:
                title += ' (%s)' % f.read().strip()
        md += ['## ' + title, '']

        # load
        load = {}
        ams = []
        with open(os.path.join(bdir, 'load.tsv')) as f:
            header = f.readline().rstrip('\n').split('\t')
            for line in f:
                r = dict(zip(header, line.rstrip('\n').split('\t')))
                load[r['am']] = r
                ams.append(r['am'])
        cols = [('copy_s', 'COPY s'), ('index_s', 'Indexes s'), ('vacuum_s', 'VACUUM ANALYZE s'),
                ('wal_load_mb', 'WAL of load MB'), ('table_mb_loaded', 'Tables MB after COPY'),
                ('table_mb', 'Tables MB'), ('toast_mb', 'TOAST MB'), ('index_mb', 'Indexes MB')]
        md += ['| AM | ' + ' | '.join(c[1] for c in cols) + ' |',
               '|---|' + '---|' * len(cols)]
        for am in ams:
            md.append('| %s | ' % am + ' | '.join(load[am].get(c[0], '') for c in cols) + ' |')
        md.append('')

        # queries
        res = {}
        order = []
        with open(os.path.join(bdir, 'results.tsv')) as f:
            for line in f:
                am, q, tr, ms, st = line.rstrip('\n').split('\t')[:5]
                if q not in order:
                    order.append(q)
                res.setdefault((am, q), []).append((int(tr), float(ms), st))

        def cold(am, q):
            t = sorted(res.get((am, q), []))
            return (t[0][1], t[0][2]) if t else (None, 'missing')

        def hot(am, q):
            t = sorted(res.get((am, q), []))
            oks = [ms for tr, ms, st in t[1:] if st == 'ok'] or [ms for tr, ms, st in t[:1] if st == 'ok']
            if oks:
                return min(oks), 'ok'
            return (t[0][1], t[0][2]) if t else (None, 'missing')

        base = ams[0]
        same = {}
        for q in order:
            ref = canonical(os.path.join(bdir, base, q + '.out'))
            for am in ams[1:]:
                other = canonical(os.path.join(bdir, am, q + '.out'))
                same[(am, q)] = ref is not None and other is not None and ref == other

        head = ['Query']
        for am in ams:
            head += ['%s cold s' % am, '%s hot s' % am]
        for am in ams[1:]:
            head += ['%s/%s hot' % (am, base), 'Answer']
        md += ['| ' + ' | '.join(head) + ' |', '|---' * len(head) + '|']
        both = {am: [] for am in ams[1:]}
        both_cold = {am: [] for am in ams[1:]}
        for q in order:
            row = [q]
            for am in ams:
                for fn in (cold, hot):
                    ms, st = fn(am, q)
                    row.append(fmt_s(ms) if st == 'ok' else '%s' % st)
            for am in ams[1:]:
                (bh, bst), (oh, ost) = hot(base, q), hot(am, q)
                (bc, bcs), (oc, ocs) = cold(base, q), cold(am, q)
                if bst == ost == 'ok':
                    row.append('%.2f' % (oh / max(bh, 0.001)))
                    both[am].append((q, bh, oh))
                else:
                    row.append('-')
                if bcs == ocs == 'ok':
                    both_cold[am].append((q, bc, oc))
                if bst != 'ok' or ost != 'ok':
                    row.append('-')
                else:
                    row.append('same' if same[(am, q)] else '**differs**')
            md.append('| ' + ' | '.join(row) + ' |')
        md.append('')
        for am in ams[1:]:
            for label, pairs in (('hot', both[am]), ('cold', both_cold[am])):
                if not pairs:
                    continue
                ratios = [o / max(h, 0.001) for q, h, o in pairs]
                md.append('- %s against %s, %s, the %d queries both finished: sum %s s against %s s; '
                          'geometric mean of the ratios %.3f; %s faster by more than 10%% in %d, slower in %d.'
                          % (am, base, label, len(pairs), fmt_s(sum(o for q, h, o in pairs)),
                             fmt_s(sum(h for q, h, o in pairs)), gmean(ratios), am,
                             sum(1 for r in ratios if r < 1 / 1.1), sum(1 for r in ratios if r > 1.1)))
            diff = [q for q in order if same.get((am, q)) is False
                    and hot(base, q)[1] == 'ok' and hot(am, q)[1] == 'ok']
            md.append('- Answers that differ from %s\'s: %s.' % (base, ' '.join(diff) if diff else 'none'))
            notok = ['%s %s (%s)' % (a, q, hot(a, q)[1]) for q in order for a in ams if hot(a, q)[1] != 'ok']
            md.append('- Not finished: %s.' % ('; '.join(notok) if notok else 'none'))
        md.append('')
    with open(os.path.join(out, 'summary.md'), 'w') as f:
        f.write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    a = sys.argv[1:]
    if len(a) == 4 and a[0] == 'tpcgen':
        tpcgen(a[1], a[2], a[3])
    elif len(a) >= 2 and a[0] == 'evict':
        evict(a[1:])
    elif len(a) == 2 and a[0] == 'report':
        report(a[1])
    else:
        sys.exit(__doc__)
